export const getProgramsByCollege = (collegeId) =>
  CHARUSAT_DATA.find((c) => c.id === collegeId)?.programs ?? [];

export const getProgramById = (collegeId, programId) =>
  getProgramsByCollege(collegeId).find((p) => p.id === programId) ?? null;

export const getYearsForProgram = (program) => {
  if (!program) return [];
  return Array.from({ length: program.duration }, (_, i) => {
    const ordinals = ["1st", "2nd", "3rd", "4th", "5th"];
    return `${ordinals[i] ?? `${i + 1}th`} Year`;
  });
};

/** Build a human-readable label for a structured audience entry */
export const audienceLabel = (entry) => {
  if (entry.audience_type === "OTHER") return entry.custom_audience || "Custom Audience";
  if (!entry.college_id) return "Entire CHARUSAT student community";
  const college = CHARUSAT_DATA.find((c) => c.id === entry.college_id);
  if (!college) return "Entire CHARUSAT student community";
  if (!entry.program_id) return `All ${college.name} students`;
  const program = college.programs.find((p) => p.id === entry.program_id);
  if (!program) return `All ${college.name} students`;
  if (!entry.year) return `All ${program.name} students (${college.name})`;
  return `${entry.year} ${program.name} (${college.name})`;
};
